"""Build the Google Sheets add-on HTML files from the shared web UI.

    python tools/build_addon.py

web/app.css + web/app.js  ->  addon/Sidebar.html   (SG_MODE = "sidebar")
                          ->  addon/Graph.html     (SG_MODE = "graph", data injected by Apps Script)

One UI code base, three shells: the standalone web app, the Sheets sidebar
and the full-screen graph dialog.
"""
import base64
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(*p):
    with open(os.path.join(ROOT, *p), encoding="utf-8") as fh:
        return fh.read()


# Static placeholder + error reporter: if the UI script cannot run inside the Sheets
# iframe, the panel says why instead of staying blank.
BOOT = """<div id="sg-boot" style="padding:16px;font:13px/1.5 sans-serif;color:#475569">Loading SheetGuard…</div>
<script>
window.onerror = function (msg, src, line, col) {
  var b = document.getElementById("sg-boot");
  if (b) {
    b.style.color = "#dc2626";
    b.textContent = "SheetGuard could not start: " + msg + " (line " + line + ":" + col + "). " +
      "Re-copy this file from the addon folder with Notepad (Ctrl+A, Ctrl+C), paste it over the whole file in Apps Script, save, then reload the sheet.";
  }
};
</script>
"""


def loader(src):
    b64 = base64.b64encode(src.encode("utf-8")).decode("ascii")
    chunks = ",\n".join('"%s"' % b64[i:i + 1000] for i in range(0, len(b64), 1000))
    return ("<script>\n(function () {\n  var b64 = [\n" + chunks + "\n  ].join(\"\");\n"
            "  var bin = atob(b64), bytes = new Uint8Array(bin.length);\n"
            "  for (var i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);\n"
            "  var el = document.createElement(\"script\");\n"
            "  el.text = new TextDecoder(\"utf-8\").decode(bytes) + \"\\n//# sourceURL=sheetguard-app.js\";\n"
            "  document.body.appendChild(el);\n"
            "})();\n</script>")


def build():
    css = read("web", "app.css")
    # The UI script is shipped base64-encoded and decoded in the browser. Apps Script's
    # HtmlService re-serialises inline <script> code before document.write()-ing it into
    # the sandbox iframe, and that rewrite broke the 120 KB script ("Invalid or unexpected
    # token"). Base64 is plain [A-Za-z0-9+/=], so nothing can be rewritten; the decoded
    # source is byte-for-byte web/app.js (errors report as sheetguard-app.js:line).
    js = loader(read("web", "app.js"))
    sidebar = f"""<!DOCTYPE html>
<html>
<head>
<base target="_top">
<meta charset="utf-8">
<!-- GENERATED by tools/build_addon.py from web/app.css + web/app.js. Do not edit by hand. -->
<style>
{css}
</style>
</head>
<body>
{BOOT}<script>window.SG_MODE = "sidebar";</script>
{js}
</body>
</html>
"""
    graph = f"""<!DOCTYPE html>
<html>
<head>
<base target="_top">
<meta charset="utf-8">
<!-- GENERATED by tools/build_addon.py. Apps Script injects the graph data below. -->
<style>
{css}
</style>
</head>
<body>
{BOOT}<script type="application/json" id="sg-data"><?!= data ?></script>
<script>
window.SG_MODE = "graph";
window.SG_DATA = JSON.parse(document.getElementById("sg-data").textContent);
</script>
{js}
</body>
</html>
"""
    os.makedirs(os.path.join(ROOT, "addon"), exist_ok=True)
    for name, text in (("Sidebar.html", sidebar), ("Graph.html", graph)):
        with open(os.path.join(ROOT, "addon", name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote addon/{name}  ({len(text) // 1024} KB)")


if __name__ == "__main__":
    build()
